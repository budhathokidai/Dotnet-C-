namespace e_escape_char;

class Program
{
    static void Main(string[] args)
    {
        // escape characters
        // 1. this will print "Rabi" in the next line.
        Console.WriteLine("Hello\nRabi");

        // 2. this will privide a tab between the words.
        Console.WriteLine("Hello\tRabi");

        // 3. lets you to print something with double quote
        Console.WriteLine("\"Hello Rabi\"");

        // 4. to print path using slash
        Console.WriteLine("D:\\SEM6\\C#\\");
    }
}
